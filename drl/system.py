"""Actor-learner RL training system (IMPALA-style architecture, PPO-style update), using only the Python
standard library's multiprocessing plus PyTorch.

  actors (N processes)                      learner (main process)
  ------------------------                  ---------------------------------------------
  copy latest weights from shared memory    pull trajectory chunks from the queue
  run the terminal simulator for T steps    drop chunks that are too stale (policy lag > max_lag)
  push (obs, action, behaviour log-prob,    PPO clipped update, ratio taken against the BEHAVIOUR
        reward, done, value, version)       policy that generated the data (corrects for lag)
  send a heartbeat after every chunk        publish new weights to shared memory, bump version
                                            supervisor: restart any actor whose heartbeat stops

Everything the learner sees is timestamped, so the run reports throughput, queue depth, policy lag and
end-to-end latency, and can inject a crash to show recovery.
"""
from __future__ import annotations

import os
import queue as queue_mod
import time
from dataclasses import asdict, dataclass

import numpy as np
import torch
import torch.multiprocessing as mp
import torch.nn as nn

from terminal_rl.env import Config, TerminalEnv
from terminal_rl.ppo import CraneScorer


@dataclass
class SysConfig:
    n_actors: int = 2
    chunk: int = 256               # decisions per trajectory chunk sent by an actor
    batch_chunks: int = 8          # chunks per learner update (8 x 256 = 2,048 decisions)
    total_steps: int = 120_000     # environment decisions to consume
    epochs: int = 3
    minibatch: int = 512
    lr: float = 3e-4
    gamma: float = 0.995
    lam: float = 0.95
    clip: float = 0.2
    ent_coef: float = 0.01
    max_lag: int = 4               # discard chunks generated by a policy more than 4 versions old
    heartbeat_timeout_s: float = 20.0
    crash_actor_at_s: float = -1   # >0: kill actor 0 this many seconds into training (fault-injection test)
    seed: int = 0
    work_per_step_ms: float = 0.0  # optional extra simulated compute per env step (heavier simulators)


# ----------------------------------------------------------------------------------------------- actor
def actor_loop(aid, cfg: SysConfig, shared_net, version, q, heartbeats, stop):
    torch.set_num_threads(1)
    rng = np.random.default_rng(cfg.seed * 1000 + aid + int(time.time() * 1000) % 100000)
    env = TerminalEnv(Config(n_trucks=int(rng.integers(8, 15))))
    net = CraneScorer(7, 3)
    obs, info = env.reset(seed=int(rng.integers(1e9)))
    mask = info["action_mask"]
    while not stop.is_set():
        net.load_state_dict(shared_net.state_dict())        # latest published weights
        ver = version.value
        O, M, A, LP, R, D, V = [], [], [], [], [], [], []
        t_first = time.time()
        for _ in range(cfg.chunk):
            o = torch.as_tensor(obs, dtype=torch.float32)[None]
            m = torch.as_tensor(mask)[None]
            with torch.no_grad():
                logits, v = net(o, env.cfg.n_cranes, m)
                dist = torch.distributions.Categorical(logits=logits)
                a = dist.sample()
            obs2, r, done, _, info = env.step(a.item())
            if cfg.work_per_step_ms > 0:
                t_end = time.perf_counter() + cfg.work_per_step_ms / 1000
                while time.perf_counter() < t_end:
                    pass
            O.append(obs); M.append(mask); A.append(a.item()); LP.append(dist.log_prob(a).item())
            R.append(r); D.append(done); V.append(v.item())
            if done:
                env.cfg = Config(n_trucks=int(rng.integers(8, 15)))
                obs, info = env.reset(seed=int(rng.integers(1e9)))
            else:
                obs = obs2
            mask = info["action_mask"]
        with torch.no_grad():
            _, last_v = net(torch.as_tensor(obs, dtype=torch.float32)[None], env.cfg.n_cranes,
                            torch.as_tensor(mask)[None])
        q.put({"aid": aid, "version": ver, "t_first": t_first, "t_sent": time.time(),
               "obs": np.array(O, np.float32), "mask": np.array(M, bool), "act": np.array(A), "logp": np.array(LP, np.float32),
               "rew": np.array(R, np.float32), "done": np.array(D, np.float32), "val": np.array(V, np.float32),
               "last_v": float(last_v.item())})
        heartbeats[aid] = time.time()


# ----------------------------------------------------------------------------------------------- learner
def gae(chunk, gamma, lam):
    r, d, v = chunk["rew"], chunk["done"], chunk["val"]
    adv, g = np.zeros_like(r), 0.0
    for t in reversed(range(len(r))):
        nv = chunk["last_v"] if t == len(r) - 1 else v[t + 1]
        delta = r[t] + gamma * nv * (1 - d[t]) - v[t]
        g = delta + gamma * lam * (1 - d[t]) * g
        adv[t] = g
    return adv, adv + v


def run(cfg: SysConfig, log=print):
    torch.manual_seed(cfg.seed)
    torch.set_num_threads(1)
    ctx = mp.get_context("spawn")
    shared = CraneScorer(7, 3)
    shared.share_memory()
    learner = CraneScorer(7, 3)
    learner.load_state_dict(shared.state_dict())
    opt = torch.optim.Adam(learner.parameters(), lr=cfg.lr)
    version = ctx.Value("i", 0)
    q = ctx.Queue(maxsize=64)
    stop = ctx.Event()
    manager = ctx.Manager()
    heartbeats = manager.dict()
    procs = {}

    def start(aid):
        heartbeats[aid] = time.time()
        p = ctx.Process(target=actor_loop, args=(aid, cfg, shared, version, q, heartbeats, stop), daemon=True)
        p.start()
        procs[aid] = p

    for aid in range(cfg.n_actors):
        start(aid)
    t0 = time.time()
    consumed, dropped, updates, crashed, restarts = 0, 0, 0, False, []
    lags, latencies, timeline, buf = [], [], [], []
    while consumed < cfg.total_steps:
        now = time.time() - t0
        if cfg.crash_actor_at_s > 0 and not crashed and now > cfg.crash_actor_at_s:
            procs[0].kill()                                   # fault injection
            crashed = True
            log(f"[{now:6.1f}s] injected crash: killed actor 0")
        for aid, p in list(procs.items()):                    # supervisor
            if not p.is_alive() or time.time() - heartbeats.get(aid, 0) > cfg.heartbeat_timeout_s:
                if p.is_alive():
                    p.kill()
                start(aid)
                restarts.append({"actor": aid, "t": round(time.time() - t0, 1)})
                log(f"[{time.time() - t0:6.1f}s] supervisor restarted actor {aid}")
        try:
            ch = q.get(timeout=1.0)
        except queue_mod.Empty:
            continue
        lag = version.value - ch["version"]
        latencies.append(time.time() - ch["t_first"])
        if lag > cfg.max_lag:
            dropped += len(ch["rew"])
            continue
        lags.append(lag)
        buf.append(ch)
        if len(buf) < cfg.batch_chunks:
            continue
        # ---- PPO update with the behaviour policy's log-probs (off-policy correction for lag)
        advs, rets = zip(*(gae(c, cfg.gamma, cfg.lam) for c in buf))
        O = torch.as_tensor(np.concatenate([c["obs"] for c in buf]))
        M = torch.as_tensor(np.concatenate([c["mask"] for c in buf]))
        A = torch.as_tensor(np.concatenate([c["act"] for c in buf]))
        LP = torch.as_tensor(np.concatenate([c["logp"] for c in buf]))
        ADV = torch.as_tensor(np.concatenate(advs))
        RET = torch.as_tensor(np.concatenate(rets))
        for _ in range(cfg.epochs):
            idx = torch.randperm(len(A))
            for s in range(0, len(A), cfg.minibatch):
                b = idx[s:s + cfg.minibatch]
                logits, v = learner(O[b], 4, M[b])
                dist = torch.distributions.Categorical(logits=logits)
                ratio = torch.exp(dist.log_prob(A[b]) - LP[b])
                ab = (ADV[b] - ADV[b].mean()) / (ADV[b].std() + 1e-8)
                loss = (-torch.min(ratio * ab, ratio.clamp(1 - cfg.clip, 1 + cfg.clip) * ab).mean()
                        + 0.5 * ((v - RET[b]) ** 2).mean() - cfg.ent_coef * dist.entropy().mean())
                opt.zero_grad(); loss.backward()
                nn.utils.clip_grad_norm_(learner.parameters(), 0.5)
                opt.step()
        with torch.no_grad():                                 # publish
            for ps, pl in zip(shared.parameters(), learner.parameters()):
                ps.copy_(pl)
        version.value += 1
        updates += 1
        n = sum(len(c["rew"]) for c in buf)
        consumed += n
        ep_ret = float(np.mean([c["rew"].sum() for c in buf]))
        timeline.append({"t": round(time.time() - t0, 2), "consumed": consumed, "version": version.value,
                         "queue_depth": q.qsize() if hasattr(q, "qsize") else -1,
                         "reward_per_chunk": round(ep_ret, 2)})
        buf = []
        if updates % 10 == 0:
            log(f"[{time.time() - t0:6.1f}s] update {updates}, consumed {consumed}, "
                f"{consumed / (time.time() - t0):.0f} decisions/s, mean lag {np.mean(lags):.2f}")
    stop.set()
    elapsed = time.time() - t0
    for p in procs.values():
        p.join(timeout=3)
        if p.is_alive():
            p.kill()
    return learner, {
        "config": asdict(cfg), "elapsed_s": round(elapsed, 1), "decisions_consumed": consumed,
        "decisions_dropped_stale": dropped, "updates": updates,
        "throughput_decisions_per_s": round(consumed / elapsed, 1),
        "policy_lag_mean": round(float(np.mean(lags)), 2), "policy_lag_p95": float(np.percentile(lags, 95)),
        "latency_s_median": round(float(np.median(latencies)), 2),
        "latency_s_p95": round(float(np.percentile(latencies, 95)), 2),
        "restarts": restarts, "timeline": timeline, "cpu_count": os.cpu_count(),
    }
